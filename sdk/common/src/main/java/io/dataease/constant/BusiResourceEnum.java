package io.dataease.constant;

/**
 * DataEase业务资源类型枚举
 * <p>
 * 定义系统中所有业务相关的资源类型，主要用于业务功能模块的分类和管理。
 * 与权限资源枚举相比，本枚举更侧重于具体的业务功能分类，
 * 用于业务逻辑处理、数据统计和功能模块区分。
 * </p>
 *
 * <p><b>业务资源分类：</b></p>
 * <ul>
 *   <li><b>分析工具</b> - 仪表板、大屏可视化</li>
 *   <li><b>数据管理</b> - 数据集、数据源管理</li>
 *   <li><b>业务应用</b> - 数据填报应用</li>
 * </ul>
 *
 * <p><b>使用场景：</b></p>
 * <ul>
 *   <li>业务模块的类型判断和分类管理</li>
 *   <li>数据统计和报表的资源类型分组</li>
 *   <li>业务功能权限的粒度控制</li>
 *   <li>系统监控和审计的资源分类标识</li>
 * </ul>
 *
 * @author fit2cloud
 * @since 1.0
 */
public enum BusiResourceEnum {
    /** 仪表板业务资源 - 互动式数据可视化仪表板，标志位:1 */
    PANEL(1),

    /** 大屏业务资源 - 全屏展示的数据可视化大屏，标志位:2 */
    SCREEN(2),

    /** 数据集业务资源 - 业务数据的逻辑视图和集合，标志位:3 */
    DATASET(3),

    /** 数据源业务资源 - 底层数据库连接和数据接口，标志位:4 */
    DATASOURCE(4),

    /** 数据填报业务资源 - 数据录入和表单管理应用，标志位:8 */
    DATA_FILLING(8);

    /**
     * 业务资源类型标志位
     * <p>
     * 唯一标识该业务资源类型的数值标识，用于业务逻辑判断、数据库存储和
     * 快速查询。与权限资源的标志位不同，此标志位主要用于业务功能的分类和识别。
     * </p>
     */
    private int flag;

    /**
     * 获取业务资源类型标志位
     * <p>
     * 返回当前业务资源类型的数值标识，用于业务逻辑判断和系统内部处理。
     * 该标志位可以用于数据库查询条件、统计分析和业务功能分类。
     * </p>
     *
     * @return 业务资源类型标志位
     */
    public int getFlag() {
        return flag;
    }

    /**
     * 设置业务资源类型标志位
     *
     * @param flag 业务资源类型标志位
     */
    public void setFlag(int flag) {
        this.flag = flag;
    }

    /**
     * 业务资源枚举构造函数
     * <p>
     * 初始化业务资源类型的标志位，为每种业务资源设定唯一的数值标识。
     * 这个标志位将用于业务逻辑中的资源类型判断和分类管理。
     * </p>
     *
     * @param flag 业务资源类型标志位
     */
    BusiResourceEnum(int flag) {
        this.flag = flag;
    }
}
