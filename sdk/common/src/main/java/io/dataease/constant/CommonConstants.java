package io.dataease.constant;

/**
 * DataEase通用常量定义类
 * <p>
 * 集中定义系统中各种通用的常量值，按功能领域分类组织，主要包括操作类型、
 * 状态标识、数据来源和业务标志等。这些常量用于统一管理和控制系统各模块的
 * 行为和状态，确保数据一致性和业务逻辑的正确性。
 * </p>
 *
 * <p><b>主要常量分类：</b></p>
 * <ul>
 *   <li><b>操作类型</b> - CRUD操作的标准定义</li>
 *   <li><b>检查结果</b> - 资源存在性和归属性检查状态</li>
 *   <li><b>视图查询</b> - 图表数据查询来源和模式定义</li>
 *   <li><b>数据来源</b> - 模板、资源表等数据来源类型</li>
 *   <li><b>发布状态</b> - 数据可视化作品的发布和管理状态</li>
 * </ul>
 *
 * <p><b>命名规范：</b></p>
 * <ul>
 *   <li>类名使用大写和下划线分隔，如 OPT_TYPE、CHECK_RESULT</li>
 *   <li>常量名使用全大写和下划线，语义明确简洁</li>
 *   <li>名称与业务场景对应，便于理解和维护</li>
 * </ul>
 *
 * @author wangjiahao
 * @author fit2cloud
 * @since 1.0
 */
public class CommonConstants {


    /**
     * 数据库操作类型常量定义
     * <p>
     * 定义系统中标准的CRUD（创建、读取、更新、删除）操作类型，用于数据库操作日志、
     * 权限控制、审计跟踪等场景。这些常量保证了操作类型标识的统一性和规范性。
     * </p>
     */
    public static final class OPT_TYPE {

        /**
         * 插入操作类型
         * <p>
         * 标识数据插入操作，用于新增数据记录、创建资源等场景。
         * 在权限控制中对应"创建"权限，在审计日志中标识"新增"操作。
         * </p>
         */
        public static final String INSERT = "insert";

        /**
         * 更新操作类型
         * <p>
         * 标识数据更新操作，用于修改现有数据记录、编辑资源属性等场景。
         * 在权限控制中对应"编辑"权限，在审计日志中标识"修改"操作。
         * </p>
         */
        public static final String UPDATE = "update";

        /**
         * 删除操作类型
         * <p>
         * 标识数据删除操作，用于删除数据记录、移除资源等场景。
         * 在权限控制中对应"删除"权限，在审计日志中标识"删除"操作。
         * </p>
         */
        public static final String DELETE = "delete";

        /**
         * 查询操作类型
         * <p>
         * 标识数据查询操作，用于读取数据记录、查看资源信息等场景。
         * 在权限控制中对应"查看"权限，在审计日志中标识"查询"操作。
         * </p>
         */
        public static final String SELECT = "select";
    }

    /**
     * 资源检查结果状态常量定义
     * <p>
     * 定义系统中资源存在性和归属性检查的各种结果状态，用于名称唯一性验证、
     * 权限归属判断、资源冲突检测等场景。这些状态帮助系统准确判断资源的
     * 存在状态和归属关系，支持精细化的权限管理和资源控制。
     * </p>
     */
    public static final class CHECK_RESULT {

        /**
         * 资源不存在状态
         * <p>
         * 表示检查的资源在系统中完全不存在，可以安全创建新资源。
         * 常用于名称唯一性检查通过的情况，允许用户使用该名称创建新资源。
         * </p>
         */
        public static final String NONE = "none";

        /**
         * 资源全局存在状态
         * <p>
         * 表示检查的资源在系统全局范围内已经存在，无法创建同名资源。
         * 用于全局唯一性要求的场景，如系统级配置、全局用户名等。
         * </p>
         */
        public static final String EXIST_ALL = "exist_all";

        /**
         * 资源在当前用户下存在状态
         * <p>
         * 表示检查的资源在当前用户的权限范围内已存在，用户可以访问和管理。
         * 常用于用户级别的资源唯一性检查，如个人仪表板、数据集名称等。
         * </p>
         */
        public static final String EXIST_USER = "exist_user";

        /**
         * 资源在其他用户下存在状态
         * <p>
         * 表示检查的资源在其他用户下存在，当前用户无权访问但名称已被占用。
         * 用于提示用户选择其他名称，避免名称冲突，同时保护其他用户的资源隐私。
         * </p>
         */
        public static final String EXIST_OTHER = "exist_other";
    }

    /**
     * 图表数据查询来源常量定义
     * <p>
     * 定义图表组件数据查询的不同来源类型，用于区分数据请求的上下文环境。
     * 不同的查询来源会影响数据缓存策略、权限验证方式和性能优化机制，
     * 确保系统在不同场景下提供最优的数据查询体验。
     * </p>
     */
    public static final class VIEW_QUERY_FROM {

        /**
         * 仪表板查看模式查询来源
         * <p>
         * 表示图表数据查询来自仪表板的正常查看模式，用户正在浏览已发布的仪表板。
         * 此模式下会启用完整的缓存机制和性能优化，提供最佳的查看体验。
         * </p>
         */
        public static final String PANEL = "panel";

        /**
         * 仪表板编辑模式查询来源
         * <p>
         * 表示图表数据查询来自仪表板的编辑模式，用户正在设计或调整仪表板布局。
         * 此模式下会减少缓存使用，确保显示最新的数据和配置变更效果。
         * </p>
         */
        public static final String PANEL_EDIT = "panel_edit";
    }

    /**
     * 图表数据查询结果模式常量定义
     * <p>
     * 定义图表数据查询时的结果返回模式，用于控制数据查询的范围和限制。
     * 不同的查询模式会影响数据量的大小、查询性能和用户体验，
     * 系统根据场景需要选择合适的查询模式来平衡性能和功能需求。
     * </p>
     */
    public static final class VIEW_RESULT_MODE {

        /**
         * 全量数据查询模式
         * <p>
         * 返回数据源中的所有匹配数据，不进行数量限制。
         * 适用于数据量相对较小或需要完整数据进行分析的场景。
         * 使用时需要注意性能和内存消耗。
         * </p>
         */
        public static final String ALL = "all";

        /**
         * 自定义数据查询模式
         * <p>
         * 根据用户设定的条件和限制返回部分数据，如TOP N、分页等。
         * 适用于大数据量场景，通过限制结果集大小来保证查询性能和用户体验。
         * </p>
         */
        public static final String CUSTOM = "custom";
    }

    /**
     * 图表编辑操作来源常量定义
     * <p>
     * 定义图表编辑操作的不同触发来源，用于区分编辑操作的上下文环境。
     * 不同的编辑来源会影响数据处理方式、缓存策略和保存机制，
     * 确保系统在不同编辑场景下提供适当的功能和性能表现。
     * </p>
     */
    public static final class VIEW_EDIT_FROM {

        /**
         * 仪表板直接编辑来源
         * <p>
         * 表示图表编辑操作来自仪表板的直接编辑模式，用户在仪表板中直接修改图表。
         * 此模式下的修改会立即影响仪表板显示，支持实时预览和快速调整。
         * </p>
         */
        public static final String PANEL = "panel";

        /**
         * 缓存数据编辑来源
         * <p>
         * 表示图表编辑操作基于缓存的数据进行，通常用于离线编辑或批量操作场景。
         * 此模式下会优先使用缓存数据，减少实时查询，提高编辑操作的响应速度。
         * </p>
         */
        public static final String CACHE = "cache";
    }

    /**
     * 图表数据读取来源常量定义
     * <p>
     * 定义图表组件数据的不同读取来源类型，用于区分数据的获取方式和处理策略。
     * 不同的数据来源具有不同的特性和用途，系统会根据来源类型采用相应的
     * 数据处理和缓存机制，确保最佳的性能和用户体验。
     * </p>
     */
    public static final class VIEW_DATA_FROM {

        /**
         * 模板数据来源
         * <p>
         * 表示图表数据来自预定义的模板，通常包含示例数据或标准配置。
         * 用于快速创建图表、演示功能或提供参考样例，数据相对固定且可重复使用。
         * </p>
         */
        public static final String TEMPLATE = "template";

        /**
         * 数据集数据来源
         * <p>
         * 表示图表数据来自用户定义的数据集，连接实际的业务数据源。
         * 这是最常用的数据来源类型，提供真实的业务数据进行分析和可视化。
         * </p>
         */
        public static final String CHART = "dataset";
    }

    /**
     * 模板来源常量定义
     * <p>
     * 定义系统中模板资源的不同来源类型，用于区分模板的获取渠道和权限范围。
     * 不同来源的模板具有不同的访问权限、使用范围和管理方式，
     * 帮助系统实现分类管理和权限控制。
     * </p>
     */
    public static final class TEMPLATE_SOURCE {
        /**
         * 模板市场来源
         * <p>
         * 表示模板来自官方或第三方的模板市场，通常为公开分享的优质模板。
         * 这类模板经过审核和优化，可供所有用户下载和使用，提供丰富的行业解决方案。
         * </p>
         */
        public static final String MARKET = "market";

        /**
         * 模板管理来源
         * <p>
         * 表示模板来自系统的模板管理功能，通常为管理员创建或维护的模板。
         * 这类模板具有更高的权限控制，可能限制特定用户群体使用。
         * </p>
         */
        public static final String MANAGE = "manage";

        /**
         * 公共模板来源
         * <p>
         * 表示模板来自公共模板库，为系统内所有用户共享的通用模板。
         * 这类模板通常包含基础的图表类型和常见的业务场景，便于快速上手使用。
         * </p>
         */
        public static final String PUBLIC = "public";
    }

    /**
     * 资源数据表类型常量定义
     * <p>
     * 定义系统中数据存储的不同表类型，用于区分数据的存储方式和访问策略。
     * 不同类型的表具有不同的特性和用途，主表用于实时数据操作，
     * 镜像表用于数据备份和历史查询，确保数据的安全性和查询性能。
     * </p>
     */
    public static final class RESOURCE_TABLE {
        /**
         * 核心主表类型
         * <p>
         * 表示系统的核心数据表，存储实时的业务数据和配置信息。
         * 主表用于日常的CRUD操作，具有最高的数据一致性和实时性要求。
         * </p>
         */
        public static final String CORE = "core";

        /**
         * 镜像快照表类型
         * <p>
         * 表示数据的镜像快照表，用于数据备份、历史查询和版本管理。
         * 快照表通常为只读模式，提供数据的历史版本访问和灾难恢复能力。
         * </p>
         */
        public static final String SNAPSHOT = "snapshot";
    }


    /**
     * 数据可视化作品发布状态常量定义
     * <p>
     * 定义数据可视化作品（如仪表板、报告等）的发布和管理状态，用于控制
     * 作品的可见性、访问权限和版本管理。不同的状态决定了作品对用户的
     * 可访问性和功能可用性，支持完整的作品生命周期管理。
     * </p>
     */
    public static final class DV_STATUS {
        /**
         * 未发布状态
         * <p>
         * 表示数据可视化作品尚未发布，仍在创建或编辑阶段。
         * 此状态下的作品仅对创建者可见，其他用户无法访问或查看。
         * 用于保护未完成的作品，避免提前暴露给最终用户。
         * </p>
         */
        public static final int UNPUBLISHED = 0;

        /**
         * 已发布状态
         * <p>
         * 表示数据可视化作品已正式发布，可供授权用户访问和使用。
         * 此状态下的作品具有完整的功能和最终的展示效果，
         * 是用户实际使用的正式版本。
         * </p>
         */
        public static final int PUBLISHED = 1;

        /**
         * 已保存但未发布状态
         * <p>
         * 表示数据可视化作品已保存最新更改但尚未重新发布。
         * 此状态通常出现在已发布作品的后续编辑过程中，
         * 新的更改需要显式发布后才能对外生效。
         * </p>
         */
        public static final int SAVED_UNPUBLISHED = 2;
    }

}
