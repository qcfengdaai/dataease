package io.dataease.constant;

/**
 * DataEase权限资源类型枚举
 * <p>
 * 定义系统中所有可管理和授权的资源类型，用于权限控制、菜单管理和资源分类。
 * 每种资源类型都对应特定的菜单ID和标志位，用于在权限系统中进行统一标识和管理。
 * </p>
 *
 * <p><b>资源分类：</b></p>
 * <ul>
 *   <li><b>数据资源</b> - 数据集、数据源、同步数据源</li>
 *   <li><b>分析工具</b> - 仪表板、大屏、汇总分析</li>
 *   <li><b>管理功能</b> - 系统管理、用户管理、角色管理、组织管理</li>
 *   <li><b>应用功能</b> - 任务管理、数据填报</li>
 * </ul>
 *
 * <p><b>数据结构：</b></p>
 * <ul>
 *   <li>menuId - 对应的菜单标识符，用于关联系统菜单</li>
 *   <li>flag - 资源类型标志位，用于权限判断和快速检索</li>
 * </ul>
 *
 * @author fit2cloud
 * @since 1.0
 */
public enum AuthResourceEnum {

    /** 仪表板资源 - 数据可视化仪表板，菜单ID:2，标志位:1 */
    PANEL(2, 1),

    /** 大屏资源 - 数据可视化大屏幕，菜单ID:3，标志位:2 */
    SCREEN(3, 2),

    /** 数据集资源 - 数据源的逻辑视图，菜单ID:5，标志位:3 */
    DATASET(5, 3),

    /** 数据源资源 - 原始数据连接，菜单ID:6，标志位:4 */
    DATASOURCE(6, 4),

    /** 系统管理资源 - 系统级配置和管理，菜单ID:7，标志位:0 */
    SYSTEM(7, 0),

    /** 用户管理资源 - 用户账户管理，菜单ID:8，标志位:5 */
    USER(8, 5),

    /** 角色管理资源 - 权限角色管理，菜单ID:8，标志位:6 */
    ROLE(8, 6),

    /** 组织管理资源 - 组织架构管理，菜单ID:9，标志位:7 */
    ORG(9, 7),

    /** 同步数据源资源 - 数据同步任务管理，菜单ID:23，标志位:9 */
    SYNC_DATASOURCE(23, 9),

    /** 任务管理资源 - 系统任务调度管理，菜单ID:24，标志位:9 */
    TASK(24, 9),

    /** 汇总分析资源 - 数据汇总和统计分析，菜单ID:22，标志位:9 */
    SUMMARY(22, 9),

    /** 数据填报资源 - 数据录入和表单管理，菜单ID:60，标志位:8 */
    DATA_FILLING(60, 8);

    /**
     * 菜单标识符
     * <p>
     * 资源对应的系统菜单ID，用于关联资源与系统菜单结构。
     * 在权限控制中，通过菜单ID可以确定用户对特定菜单项的访问权限。
     * </p>
     */
    private long menuId;

    /**
     * 资源类型标志位
     * <p>
     * 唯一标识该资源类型的数值标识，用于权限判断、索引查询和数据库存储。
     * 每种资源类型对应不同的标志位值，便于快速识别和分类。
     * </p>
     */
    private int flag;

    /**
     * 获取资源对应的菜单标识符
     * <p>
     * 返回当前资源类型在系统菜单中的唯一标识符。
     * 这个ID用于关联资源与菜单结构，实现权限控制和导航管理。
     * </p>
     *
     * @return 菜单标识符
     */
    public long getMenuId() {
        return menuId;
    }

    /**
     * 设置资源对应的菜单标识符
     *
     * @param menuId 菜单标识符
     */
    public void setMenuId(long menuId) {
        this.menuId = menuId;
    }

    /**
     * 获取资源类型标志位
     * <p>
     * 返回当前资源类型的数值标识，用于权限判断、快速检索和数据存储。
     * 每个资源类型都有唯一的标志位，便于系统内部识别和管理。
     * </p>
     *
     * @return 资源类型标志位
     */
    public int getFlag() {
        return flag;
    }

    /**
     * 设置资源类型标志位
     *
     * @param flag 资源类型标志位
     */
    public void setFlag(int flag) {
        this.flag = flag;
    }

    /**
     * 权限资源枚举构造函数
     * <p>
     * 初始化资源类型的菜单ID和标志位，建立资源与菜单系统的对应关系。
     * 这两个参数组合起来唯一定义了一种资源类型在系统中的身份和地位。
     * </p>
     *
     * @param menuId 菜单标识符，用于关联系统菜单
     * @param flag 资源类型标志位，用于内部识别和管理
     */
    AuthResourceEnum(long menuId, int flag) {
        this.menuId = menuId;
        this.flag = flag;
    }
}
